function cleanOldOrderOffline(scope) {
  const cli = join(host.home,'profiles','web','node_modules','dsh-chief','bin','cli.mjs')
  const command = (...args) => JSON.parse(execFileSync(process.execPath,[cli,'cleanup-legacy-orders','--brain',host.brain,...args],{encoding:'utf8'}))
  const preview = command()
  assert.equal(preview.scope,scope)
  assert.ok(preview.ticketIds.includes(legacyId))
  assert.deepEqual(preview.blockers,[])
  assert.ok(existsSync(legacyTicket), '预览未清理源记录')
  const applied = command('--apply',preview.id)
  assert.ok(applied.backup, '清理留下可恢复副本')
  assert.ok(!existsSync(legacyTicket))
  assert.ok(!existsSync(legacyWork))
}
