  assert.match(importId,/^profile-[a-f0-9]{64}$/)
  await desktop.getByRole('heading',{name:'核对资料',exact:true}).waitFor()
  const reviewed = await until(async () => {
    const {record} = await detail(importId)
    return record.status === 'review' && record
  },'资料已整理')
  assert.equal(reviewed.items[0].quote,original)
  assert.ok(!readFileSync(join(host.brain,'me.md'),'utf8').includes('讲清楚取舍'), '核对前还没有写入资料')

  await mobile.bringToFront()
  await mobile.goto(host.mobileBase + '/#v2?' + new URLSearchParams({scope,view:'profile',item:importId}))
  await mobile.getByRole('heading',{name:'核对资料',exact:true}).waitFor()
  await button(mobile,'采纳').click()
  const saved = await until(async () => {
    const {record} = await detail(importId)
    return record.status === 'processed' && record.items[0].saved
  },'手机已保存确认资料')
  assert.equal(saved.text,'我习惯在设计评审里先讲清楚取舍。')
  assert.ok(readFileSync(join(host.brain,'me.md'),'utf8').includes(saved.text))
  await picture(mobile,'mobile-profile-import')

  await desktop.bringToFront()
  await button(desktop,'今天').click()
  await button(desktop,/^一句话交办(，|$)/).click()
  const liaison = desktop.getByRole('dialog',{name:'接口人'})
  const paste = '我有一份仅在内部讨论的笔记。 [对话] [机密]'
  const ownerTurn = '这是另一个助手对我的了解，帮我导入。\n' + paste
  await liaison.getByLabel('对接口人说').fill(ownerTurn)
  await button(liaison,'发送').click()
  await button(liaison,'核对资料').click()
  await desktop.getByRole('heading',{name:'核对资料',exact:true}).waitFor()
  await desktop.getByLabel('保存到').selectOption('new')
  await button(desktop,'采纳').click()
  const fromChat = new URLSearchParams(new URL(desktop.url()).hash.slice(4)).get('item')
  assert.ok(fromChat && fromChat !== importId)
  await until(async () => (await detail(fromChat)).record.status === 'processed','接口人回执可保存')
  assert.equal((await detail(fromChat)).record.text,ownerTurn)
  assert.ok(readFileSync(join(host.brain,'me.md'),'utf8').includes('仅在内部讨论的笔记'))
